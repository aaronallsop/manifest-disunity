/*
 * Fetch a baked JSON file, never from the HTTP cache.
 *
 * `data/*.json` is regenerated by the scripts in build/, and a browser that
 * replays a stale copy runs the game against a world that no longer exists —
 * silently, and with no way to tell from inside the page. That is not
 * hypothetical: a cache entry written before the dev server started sending
 * no-store survived every reload, so the game kept booting Hawaii with no
 * adjacency and sixteen movements instead of twenty-four, hours after the bake.
 *
 * This is what the hand-bumped `?v=` query strings in index.html were reaching
 * for. `cache: 'no-store'` says it once, correctly, and needs no maintenance.
 */
const getJSON = (path, fallback) =>
  fetch(path, { cache: 'no-store' })
    .then((r) => {
      if (!r.ok) throw new Error(`${path}: HTTP ${r.status}`);
      return r.json();
    })
    .catch((err) => {
      if (fallback === undefined) throw err;  // required file: fail the boot loudly
      console.warn('optional data file unavailable:', err.message);
      return fallback;
    });

async function init() {
  try {
    const [topo, data, ctGeo, adjacency, neighbors, partyDefs, trade, areas, geoMode, economy, transport, cultureMode, tunables, ideologies, capitals, eventDefs, leaderDefs, nameDefs] = await Promise.all([
      getJSON('data/counties-10m.json'),
      getJSON('data/game-data.json'),
      getJSON('data/ct-planning-regions.geojson'),
      getJSON('data/adjacency.json'),
      getJSON('data/county_neighbors.json', {}),
      getJSON('data/parties.json', {}),
      getJSON('data/county_trade.json', null),
      getJSON('data/areas.json', null),
      getJSON('content/geographical.json', null),
      getJSON('data/economy.json', null),
      getJSON('data/transport.json', null),
      getJSON('content/cultural.json', null),
      getJSON('content/tunables.json', null),
      getJSON('content/ideologies.json', null),
      getJSON('content/capitals.json', null),
      getJSON('content/events.json', null),
      getJSON('content/leaders.json', null),
      getJSON('content/names.json', null),
    ]);
    // The six ideologies, before anything reads a political value.
    Ideology.load(ideologies);
    // Authored tunable overrides, applied over the schema defaults in js/tunables.js.
    if (tunables) {
      const unknown = TUNE.load(tunables.values || tunables);
      if (unknown.length) console.warn('content/tunables.json: unknown keys ignored:', unknown);
    }
    // Seeded RNG, created before anything draws. Everything downstream takes it
    // explicitly; nothing reads it off a module global.
    store.seed = RNG.newSeed();
    store.rng = RNG.create(store.seed);

    OLD_CT_TO_REGION = GeoCT.OLD_CT_TO_REGION;
    OLD_CT = GeoCT.OLD_CT;

    store.data = data;
    store.topo = topo;
    store.areasDef = areas; // the build stamp a save is validated against
    store.neighbors = neighbors; // Census County Adjacency File (fips -> [fips])
    store.trade = trade;         // offline-baked trade attributes (county_trade.json)
    store.transport = transport; // rail / interstates / Canada-Mexico gateways (transport.json)
    Ledger.reset();
    Relations.reset();
    Recognition.reset();
    Migration.reset();
    Coalitions.reset();
    Colors.assign(Object.keys(data.states));
    Game.init(data, adjacency, areas, { trade, transport, culture: cultureMode });
    const emerged = Parties.setup(partyDefs, store.rng); // setup-only regional party spawns
    MapModes.init(data);
    if (geoMode && geoMode.type === 'ns-mapmode') MapModes.setRegion(geoMode); // published in the editor
    if (cultureMode && cultureMode.type === 'ns-mapmode') MapModes.setCulture(cultureMode);
    if (economy) MapModes.setEconomy(economy); // baked six-sector production values
    if (economy) Market.update(TUNE); // opening market prices
    // The seats of government, resolved through the Area alias — several capital
    // counties are merged into a larger Area, and a raw FIPS lookup would miss
    // them silently (the M1.13 trap).
    if (capitals) Victory.load(capitals);
    Events.reset();
    if (eventDefs) Events.load(eventDefs);
    Leaders.reset();
    if (leaderDefs) Leaders.load(leaderDefs);
    // Loaded BEFORE Game.init, because the first thing a breakaway needs is a name.
    if (nameDefs) Identity.load(nameDefs);
    TurnSystem.begin([...Game.nations.keys()], store.rng);
    choosePlayer();
    World.begin(TUNE, null, store.rng); // the power stocks and the leaders
    if (emerged.length) {
      setTimeout(() => flash(`\u{1F5F3} Regional parties emerged: <strong>${emerged.map(escapeHtml).join('</strong>, <strong>')}</strong>.`, 'warn'), 300);
    }
    Game.onChange(onGameChange);
    buildMap(topo, ctGeo);
    wireControls();

    /*
     * Resume from the live document if there is one.
     *
     * Done AFTER the map is built, because applying a document emits and the
     * renderer has to exist to hear it — and after a full fresh world has been
     * assembled, so a document that turns out to be unreadable leaves a playable
     * game rather than a blank map. `?fresh=1` skips the resume without deleting
     * anything; the Load dialog is where documents are managed deliberately.
     */
    let freshGame = true;
    if (!new URLSearchParams(location.search).has('fresh')) {
      const live = await SaveManager.readLive();
      if (live) {
        const res = SaveManager.apply(live);
        if (res.ok) {
          freshGame = false;
          flash('\u{1F4BE} Resumed at world turn <strong>' + World.getTurn() + '</strong> from '
            + 'data/state.json. Add <code>?fresh=1</code> to the URL to start over.', '');
        } else {
          console.warn('state.json was not loadable, starting fresh:', res.message);
          flash('\u{26A0} The saved world could not be resumed (' + escapeHtml(res.message)
            + ') so this is a fresh game.', 'warn');
        }
      }
    }

    /*
     * A resumed document carries its own player; a document written before M6.2
     * carries none, and so does a fresh game whose `choosePlayer` ran against
     * the pre-resume world. Either way, settle it before the first sweep — a
     * sweep with no player declines to run, and the symptom would be a game that
     * simply never lets the AI move.
     */
    if (!Game.playerNation()) choosePlayer();
    // ...and hand the seat back to the human, wherever in the order the load left
    // the pointer.
    AI.sweep(TUNE, store.rng);

    Leaderboard.refresh();
    renderTurnBanner();
    select('nation', you());
    document.getElementById('loading')?.remove();

    /*
     * The faction picker, for a genuinely new game only: not after a resume,
     * which already knows who you were, and not when `?play=` has answered the
     * question. `choosePlayer` has already seated somebody, so cancelling out of
     * this leaves a playable game rather than a blank one.
     */
    if (freshGame && !new URLSearchParams(location.search).get('play')) {
      showStart((nid) => {
        const r = Factions.choose(nid, TUNE);
        store.playerName = Game.playerNation() ? Game.playerNation().name : null;
        TurnSystem.seat(nid);
        Leaderboard.refresh();
        renderTurnBanner();
        setMode('nations');
        select('nation', nid);
        if (r) {
          flash(`\u{1F3DB}\u{FE0F} You are <strong>${escapeHtml(r.name)}</strong> — <strong>${escapeHtml(r.label)}</strong>. `
            + escapeHtml(r.blurb)
            + (r.bonus > 0 ? ` Opening grant <strong>${fmtGdp(r.bonus)}</strong>.` : ''), '');
        }
      });
    }
  } catch (err) {
    const el = document.getElementById('loading');
    if (el) el.textContent = 'Could not load map data. Start the local server with `python server.py` and reload (see README.md).';
    console.error(err);
  }
}

/*
 * WHO YOU ARE.
 *
 * M6.4 puts a faction picker in front of this. Until then the seat is assigned
 * from the seed — the nation at the head of the shuffled turn order — and
 * `?play=<id or name>` overrides it, which is how a particular situation gets
 * played twice. Assigning rather than asking is the deliberate choice for M6.2:
 * the milestone is about there BEING one seat, and a chooser landing in the same
 * commit would hide whether the seat works.
 */
function choosePlayer() {
  const wanted = new URLSearchParams(location.search).get('play');
  let pick = null;
  if (wanted) {
    const key = wanted.trim().toLowerCase();
    for (const [id, n] of Game.nations) {
      if (id === wanted || n.name.toLowerCase() === key) { pick = id; break; }
    }
    if (!pick) console.warn(`?play=${wanted} names no nation; falling back to the turn order.`);
  }
  Game.setPlayer(pick || TurnSystem.currentId());
  // Remembered for the defeat screen, which has to name a nation that no longer
  // exists — `Game.getPlayer()` keeps the id, but the name lives on the record.
  store.playerName = Game.playerNation() ? Game.playerNation().name : null;
  // ...and start the game on your own slot rather than sweeping the AI round to
  // reach it. A fresh world has not begun yet; nobody is owed a turn in it.
  TurnSystem.seat(Game.getPlayer());
}

/** The nation the human is playing. Null only in a world nobody is playing. */
const you = () => Game.getPlayer();

/*
 * WHO DO YOU WANT TO BE.
 *
 * Shown once, before a fresh game, and skipped entirely when `?play=` names a
 * seat or a saved document already knows who you were — a start screen that
 * appears in front of a game already in progress is a start screen nobody wants
 * to see twice.
 *
 * Every nation is listed, because restricting it to a curated two dozen would be
 * an arbitrary line through a map whose whole premise is that every state is a
 * country now. The tier does the steering instead, and it says WHY: "Rhode
 * Island's problem is room to grow — 0% of its neighbours are smaller" is a
 * sentence a new player can act on, where "hard" is not.
 */
function showStart(onPick) {
  const el = document.getElementById('startscreen');
  const card = el.querySelector('.start-card');
  const rated = Factions.list(TUNE);
  let filter = 'all';

  const draw = () => {
    const rows = rated.filter((r) => filter === 'all' || r.tier === filter);
    card.querySelector('.start-list').innerHTML = rows.map((r) => `
      <button class="fac" data-nid="${r.nid}">
        <span class="fac-top">
          <span class="dot" style="background:${r.color}"></span>
          <span class="nm">${escapeHtml(r.name)}</span>
          <span class="tier tier-${r.tier}">${escapeHtml(r.label)}</span>
        </span>
        <span class="why">${escapeHtml(r.summary)}</span>
        ${r.bonus > 0 ? `<span class="grant">Opening grant ${fmtGdp(r.bonus)}</span>` : ''}
      </button>`).join('');
    card.querySelectorAll('.fac').forEach((b) => {
      b.onclick = () => { el.classList.remove('show'); onPick(b.dataset.nid); };
    });
    card.querySelectorAll('.start-tabs button').forEach((b) => {
      b.classList.toggle('active', b.dataset.tier === filter);
    });
  };

  const tabs = [{ id: 'all', label: `All ${rated.length}` }]
    .concat(Factions.TIERS.slice().reverse().map((t) => ({
      id: t.id, label: `${t.label} (${rated.filter((r) => r.tier === t.id).length})`,
    })));

  card.innerHTML = `
    <h2>Choose a nation</h2>
    <p class="start-sub">Every U.S. state is its own country. Pick one and hold it together — or put
      the Union back. The map is the same whoever you play; a harder start begins with a larger
      treasury instead.</p>
    <div class="start-tabs">${tabs.map((t) =>
      `<button data-tier="${t.id}">${escapeHtml(t.label)}</button>`).join('')}</div>
    <div class="start-list"></div>`;
  card.querySelectorAll('.start-tabs button').forEach((b) => {
    b.onclick = () => { filter = b.dataset.tier; draw(); };
  });
  draw();
  el.classList.add('show');
}

