/*
 * Nation States - a map game where every U.S. state becomes its own nation.
 *
 * Rendering is driven by Game ownership: each county is filled with its owning
 * nation's color, and the heavy borders are the boundaries between nations. As
 * actions move counties around, the map re-renders from the model.
 */

const WIDTH = 975;
const HEIGHT = 610;

// Connecticut's old counties still live in the base geometry. The mapping and
// the reasoning live in js/geo-ct.js so tests/ can reach them; boot-globals.js
// publishes the module as window.GeoCT.
//
// BOUND IN init(), NOT HERE. boot-globals.js is a deferred module, so it has not
// run yet while this classic script is being evaluated. Reading an ESM-bridged
// global at top level is a load-time TypeError.
let OLD_CT_TO_REGION = null;
let OLD_CT = null;

const store = {
  mode: 'nations', // 'nations' | 'counties'
  colorMode: 'standard', // 'standard' | 'political' | 'gdp' | 'population'
  data: null,
  topo: null,
  path: null,
  g: null,
  svg: null,
  hoverShape: null,
  selectShape: null,
  actionLayer: null,
  countyPaths: null,
  nationBorders: null,
  countyById: new Map(),
  outlineCache: new Map(),
  selectGlow: null,
  hoverKey: null, // what the hover outline currently shows; the mousemove guard
  selected: null, // { level:'nation'|'county', id }
  rng: null,      // seeded RNG for this session (js/rng.js); serialized in the save
  seed: null,
  // ?dev=1 exposes the manual world-step control. M5 grows the dashboard and the
  // 50-turn simulator out of the same flag.
  dev: new URLSearchParams(location.search).has('dev'),
};

